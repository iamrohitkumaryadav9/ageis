"""Read-only access to generated benchmark results (``results/aegis-ir/<run>/summary.json``).

The API never computes or edits a benchmark number: it serves what ``aegis.evaluation.report``
wrote, with each metric under its explicit name and with its population attached.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from fastapi import APIRouter, Depends

from aegis.services.core import AegisService
from aegis.services.errors import ConflictError, NotFoundError, Principal
from apps.api.deps import get_service, require

router = APIRouter(prefix="/evaluation", tags=["evaluation"])
_RUN_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
DETECTION_METRICS = ("overall_fault_detection", "drift_detection")


def _results_dir(service: AegisService) -> Path:
    return service.settings.results_dir


def _load(service: AegisService, name: str) -> dict[str, Any]:
    if not _RUN_NAME.match(name):
        raise NotFoundError(f"benchmark run {name!r} not found")
    path = _results_dir(service) / name / "summary.json"
    if not path.is_file():
        raise NotFoundError(f"benchmark run {name!r} not found")
    try:
        summary = json.loads(path.read_text())
    except (OSError, ValueError) as exc:
        raise ConflictError(f"summary of run {name!r} is unreadable: {type(exc).__name__}") from exc
    if "headline_metrics" not in summary:
        raise ConflictError(
            f"summary of run {name!r} was generated by an older report version; "
            f"regenerate it with: python -m aegis.evaluation.report --name {name}"
        )
    return summary


def _detection(summary: dict[str, Any], name: str) -> dict[str, Any]:
    block = summary["detection"][name]
    return {
        "metric_prefix": name,
        "definition": block["definition"],
        "positive_condition": block["positive_condition"],
        "population": block["population"],
        "confusion": block["confusion"],
        "metrics": {
            f"{name}_{suffix}": block[f"{name}_{suffix}"]
            for suffix in ("precision", "recall", "false_positive_rate", "f1")
        },
    }


def _config(block: dict[str, Any] | None) -> dict[str, Any] | None:
    if not block or not block.get("diagnosis"):
        return None
    diagnosis, remediation, agent = block["diagnosis"], block.get("remediation"), block.get("agent")
    out: dict[str, Any] = {
        "scenarios_diagnosed": diagnosis["scenarios_diagnosed"],
        "root_cause_top1": diagnosis["top1"],
        "root_cause_recall_at_3": diagnosis["recall_at_3"],
        "claim_validation": diagnosis.get("claim_validation"),
        "latency_ms": (agent or {}).get("latency_ms"),
        "unauthorized_tool_executions": (agent or {}).get("unauthorized_tool_executions"),
        "remediation": None,
    }
    if remediation:
        lifecycle = remediation["lifecycle"]
        out["remediation"] = {
            "counts": remediation["counts"],
            "simulation_note": remediation["simulation_note"],
            "rates": {
                key: remediation[key]
                for key in (
                    "validation_success_rate",
                    "supported_fault_remediation_success",
                    "execution_resolution_rate",
                    "rollback_success_rate",
                )
            },
            "invalid_promotions": remediation["invalid_promotions"],
            "lifecycle": {
                "reconciled": lifecycle["reconciled"],
                "events": lifecycle["events"],
                "proposals": lifecycle["proposals"],
                "derived_events": lifecycle["derived_events"],
                "terminal_status_counts": lifecycle["terminal_status_counts"],
                "accounting_identities": lifecycle["accounting_identities"],
                "failure_counts": lifecycle["failure_counts"],
            },
        }
    return out


@router.get("/runs")
def runs(
    service: AegisService = Depends(get_service), _: Principal = Depends(require("viewer"))
) -> dict:
    root = _results_dir(service)
    found = []
    if root.is_dir():
        for path in sorted(root.iterdir()):
            if path.is_dir() and _RUN_NAME.match(path.name) and (path / "summary.json").is_file():
                found.append(path.name)
    return {"runs": found}


@router.get("/runs/{name}")
def run(
    name: str,
    service: AegisService = Depends(get_service),
    _: Principal = Depends(require("viewer")),
) -> dict:
    summary = _load(service, name)
    design = summary.get("design") or {}
    return {
        "name": summary["name"],
        "n_scenarios": summary["n_scenarios"],
        "seeds": design.get("seeds"),
        "llm_model": design.get("llm_model"),
        "methodology": design.get("methodology") or [],
        "detection": [_detection(summary, name) for name in DETECTION_METRICS],
        "targets": summary["targets"],
        "full_grid": {c: _config(summary["full_grid"].get(c)) for c in ("A", "B")},
        "llm_subset": {
            "n": summary["llm_subset"]["n"],
            "configs": {
                c: _config(summary["llm_subset"]["configs"].get(c)) for c in ("A", "B", "C", "D")
            },
        },
        "resources": summary.get("resources"),
    }
